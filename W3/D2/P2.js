//Comparison operators
console.log("Comparison operators");
let x=2;
let y='3';
console.log("x==y: ",x==y);//loose equality (only compares)
console.log("x===y: ",x===y);//strict equality ( compares whith data type)
console.log("x!=y: ",x!=y);//loose inequality (only compares)
console.log("x!==y: ",x!==y);//strict inequality
console.log("x>3: ",x>3);
console.log("x<3: ",x<3);
console.log("x>=3: ",x>=3);
console.log("x<=3: ",x<=3);

