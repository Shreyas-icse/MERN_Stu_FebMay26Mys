//Arithmetic Operators
const a=2;
const b = 2;
//let c= 0;
console.log("Arithmetic Operators");
console.log("a+b: ",a+b);
console.log("a-b: ",a-b);
console.log("a*b: ",a*b);
console.log("a/b: ",a/b);
console.log("a%b: ",a%b); //modulus
console.log("a**b: ",a**b);//exponential
console.log("a++: ",a++); //post-increment
console.log("++a: ",++a);// pre-increment
console.log("a--: ",a--); //post-decrement
console.log("--a: ",--a); //post-decrement